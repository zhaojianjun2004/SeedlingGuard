/**
 ******************************************************************************
 * @file    field_services.h
 * @brief   现场业务服务入口接口定义。
 * @details 应用仅调用初始化和任务入口，不直接操作服务内部队列或共享状态。
 *
 * 项目：智能育苗室环境监测与远程告警系统
 * 层次：业务服务层
 ******************************************************************************
 */

#pragma once
/*--------------------------- 头文件 ---------------------------*/
#include <stdbool.h>

/*--------------------------- 对外接口 ---------------------------*/

/**
 * @brief 建立现场队列、状态互斥量和默认配置。
 * @return true 表示操作完成或检查通过；false 表示失败、未就绪或条件不满足。
 */
bool field_services_init(void);

/**
 * @brief 有界处理命令/样本，接收配置提交结果并检查新鲜度。
 * @note 任务入口，只在任务上下文运行；正常情况下不返回。
 */
void field_state_service_run(void);

/**
 * @brief 轮询到期设备，执行有界重试并更新离线探测调度。
 * @note 任务入口，只在任务上下文运行；正常情况下不返回。
 */
void acquisition_service_run(void);

/**
 * @brief 处理串口/诊断命令并周期发送现场快照。
 * @note 任务入口，只在任务上下文运行；正常情况下不返回。
 */
void field_link_service_run(void);

/**
 * @brief 加载现场持久状态，发布启动就绪后独占存储循环。
 * @note 任务入口，只在任务上下文运行；正常情况下不返回。
 */
void storage_service_run(void);

/**
 * @brief 按任务健康期限统一门控 IWDG 并定期输出诊断。
 * @note 任务入口，只在任务上下文运行；正常情况下不返回。
 */
void supervisor_service_run(void);
